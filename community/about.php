                    <h2>Our Mission & Name</h2>
                    <p><strong>Why "Muffeia"?</strong> The name represents our core philosophy: creating a <strong>"muffled space"</strong> where emotions can be safely expressed. "Muff" symbolizes the protected, judgment-free environment we've built, while "feia" (from "feeling" + "idea") represents transforming emotional expression into collective problem-solving.</p>
                    
                    <p>Muffeia began as a Computer Science student project with a simple but powerful mission: to create a safe digital space where people can express their emotions, share their struggles, and find genuine support without fear of judgment. We transform what might start as rants or frustrations into constructive conversations through community support.</p>
                    
                    <p>As students, we've witnessed firsthand how the pressures of academic life and social media can impact mental health. Traditional platforms often promote curated perfection rather than authentic human experience. Muffeia is our attempt to build an alternative - a platform focused on empathy, understanding, and genuine connection.</p>
                    
                    <h2>Our Story</h2>
                    <p>The idea for Muffeia emerged during a university project focused on technology for social good. As Computer Science students, we wanted to apply our technical skills to address a real-world problem we saw around us - the lack of safe digital spaces for emotional vulnerability.</p>
                    
                    <p><strong>The Name Inspiration:</strong> We chose "Muffeia" because it perfectly captures what we're building. Just like a soundproof room muffles noise to create a safe acoustic space, Muffeia creates a digital space that "muffles" social judgment while amplifying empathy and support. It's where raw emotions get transformed into shared understanding.</p>
                    
                    <p>What started as a class project has grown into a passion project that we continue developing in our spare time. We're learning as we build, applying our coursework in web development, databases, and security to create a platform that truly helps people.</p>
                    
                    <p>Though we're still students, we're committed to maintaining and improving Muffeia as a free resource for anyone needing emotional support. The name reminds us daily of our purpose: creating muffled spaces where feelings can be safely expressed and collectively resolved.</p>
